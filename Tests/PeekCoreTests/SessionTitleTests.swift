import XCTest
@testable import PeekCore

final class SessionTitleTests: XCTestCase {
    func testPromptSkipsInjectedAndCommands() {
        XCTAssertNil(SessionTitle.prompt("<system-reminder>Some injected text</system-reminder> hello"))
        XCTAssertNil(SessionTitle.prompt("<agent-message from=\"worker\">status"))
        XCTAssertNil(SessionTitle.prompt("<task-notification><task-id>abc</task-id>"))
        XCTAssertNil(SessionTitle.prompt("<command-name>/foo</command-name>"))
        XCTAssertNil(SessionTitle.prompt("/deploy staging now"))
        XCTAssertNil(SessionTitle.prompt("/deploy"))
        XCTAssertNil(SessionTitle.prompt("Caveat: The messages below were generated by the user"))
        XCTAssertNil(SessionTitle.prompt("   "))
    }

    func testPromptStripsMarkupAndPastedBlocks() {
        XCTAssertEqual(SessionTitle.prompt("<b>Fix</b> the login bug"), "Fix the login bug")
        XCTAssertEqual(SessionTitle.prompt("<pasted_content id=\"1\">line one\nline two</pasted_content>\nfix this crash"), "fix this crash")
        XCTAssertEqual(SessionTitle.prompt("[Pasted text #1 +12 lines] why does this fail"), "why does this fail")
        XCTAssertNil(SessionTitle.prompt("<pasted_content id=\"1\">cut off before the closing tag"))
        XCTAssertNil(SessionTitle.prompt("[Image #1]"))
        XCTAssertEqual(SessionTitle.prompt("# Add dark mode"), "Add dark mode")
        XCTAssertEqual(SessionTitle.prompt("/usr/local/bin is missing"), "/usr/local/bin is missing")
    }

    func testPlaceholderNames() {
        for n in ["pasted-7595", "pasted-75955e43eafd", "Pasted_1234", "a1b2c3d4", "0123456789ab", "02ad636a-9f78-410d-a846-1efa06783fb3", ""] {
            XCTAssertTrue(SessionTitle.isPlaceholder(n), n)
        }
        for n in ["peek fixes", "pasted notes", "checkout flow"] { XCTAssertFalse(SessionTitle.isPlaceholder(n), n) }
    }

    func testShortCutsAtWordBoundary() {
        XCTAssertEqual(SessionTitle.short("short", 20), "short")
        XCTAssertEqual(SessionTitle.short("refactor the payments gateway adapter", 20), "refactor the\u{2026}")
        XCTAssertEqual(SessionTitle.short("alpha beta gamma delta", 10), "alpha beta\u{2026}")
        XCTAssertEqual(SessionTitle.short("supercalifragilisticexpialidocious", 10), "supercalif\u{2026}")
    }

    func testPickOrderAndPlaceholderRanking() {
        typealias S = SessionTitle
        XCTAssertEqual(S.pick(name: "Billing", prompt: "fix the bug", cwdBase: "repo", previous: nil).title, "Billing")
        XCTAssertEqual(S.pick(name: "", prompt: "fix the bug", cwdBase: "repo", previous: nil).title, "fix the bug")
        XCTAssertEqual(S.pick(name: "", prompt: "", cwdBase: "repo", previous: nil).title, "repo")
        // a placeholder name ranks below the first genuine prompt, above the folder
        XCTAssertEqual(S.pick(name: "pasted-7595", prompt: "fix the bug", cwdBase: "repo", previous: nil).title, "fix the bug")
        XCTAssertEqual(S.pick(name: "pasted-7595", prompt: "", cwdBase: "repo", previous: nil).source, .placeholder)
    }

    func testPickIsSticky() {
        typealias S = SessionTitle
        let fallback = S.pick(name: "", prompt: "", cwdBase: "repo", previous: nil)
        let better = S.pick(name: "", prompt: "add search", cwdBase: "repo", previous: fallback)
        XCTAssertEqual(better.title, "add search")                        // a better source replaces a fallback
        let worse = S.pick(name: "", prompt: "", cwdBase: "other", previous: better)
        XCTAssertEqual(worse.title, "add search")                         // never the other way
        let named = S.pick(name: "Search work", prompt: "add search", cwdBase: "repo", previous: better)
        XCTAssertEqual(named.title, "Search work")
        let renamed = S.pick(name: "Search v2", prompt: "", cwdBase: "repo", previous: named)
        XCTAssertEqual(renamed.title, "Search v2")                        // same rank: the newer name wins
    }

    func testSentenceSkipsBoilerplate() {
        let msg = "\u{1F4CA} Memory: 1481 notes \u{00B7} peek (new)\n<!--CAPTURE: x || type: win-->\n---\n## Heading\n\nFixed the login bug in two places. Tests pass."
        XCTAssertEqual(SessionTitle.sentence(msg), "Fixed the login bug in two places")
        XCTAssertEqual(SessionTitle.sentence("\u{2705} done\n- **Updated** the config file"), "Updated the config file")
        XCTAssertEqual(SessionTitle.sentence("<!-- one\ntwo -->\nReal text"), "Real text")
        XCTAssertEqual(SessionTitle.sentence("```swift\nlet x = 1"), "let x = 1")
        XCTAssertEqual(SessionTitle.sentence("Edited main.swift and Store.swift"), "Edited main.swift and Store.swift")
        XCTAssertEqual(SessionTitle.sentence("\u{1F4CA} only a status line"), "")
        XCTAssertEqual(SessionTitle.sentence("one two three four five six seven", 14), "one two three\u{2026}")
    }
}
